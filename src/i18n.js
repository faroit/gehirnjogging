export function normaliseLocale(value) {
  const language = String(value || "").trim().toLowerCase().split(/[-_]/)[0];
  return SUPPORTED_LOCALES.includes(language) ? language : "en";
}

function supportedLocale(value) {
  const language = String(value || "").trim().toLowerCase().split(/[-_]/)[0];
  return SUPPORTED_LOCALES.includes(language) ? language : null;
}

export function detectBrowserLocale(preferences = []) {
  const requested = Array.isArray(preferences) ? preferences : [preferences];
  return requested.map(supportedLocale).find(Boolean) || "en";
}

export function initialLocale() {
  try {
    const saved = localStorage.getItem("twenty-locale-v1");
    if (saved) return normaliseLocale(saved);
  } catch { /* Storage can be unavailable in private mode. */ }

  if (typeof navigator === "undefined") return "en";
  const preferences = [...(navigator.languages || []), navigator.language];
  return detectBrowserLocale(preferences);
}

export function rememberLocale(locale) {
  try { localStorage.setItem("twenty-locale-v1", normaliseLocale(locale)); } catch { /* Keep the picker usable without storage. */ }
}

export function translate(locale, key, parameters = {}) {
  const selected = messages[normaliseLocale(locale)] || messages.en;
  const template = selected[key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => parameters[name] ?? `{${name}}`);
}

export function missingTranslationKeys(locale) {
  const selected = messages[normaliseLocale(locale)] || messages.en;
  return Object.keys(messages.en).filter((key) => !(key in selected));
}

export function applyDocumentTranslations(locale, root = document) {
  const language = normaliseLocale(locale);
  root.documentElement.lang = language;
  root.title = translate(language, "meta.title");
  root.querySelector('meta[name="description"]')?.setAttribute("content", translate(language, "meta.description"));

  for (const element of root.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(language, element.dataset.i18n);
  }
  for (const element of root.querySelectorAll("[data-i18n-html]")) {
    element.innerHTML = translate(language, element.dataset.i18nHtml);
  }
  for (const element of root.querySelectorAll("[data-i18n-aria-label]")) {
    element.setAttribute("aria-label", translate(language, element.dataset.i18nAriaLabel));
  }
}

const numberFormatters = new Map();

export function formatDecimal(locale, value, precision = 1) {
  const language = normaliseLocale(locale);
  const key = `${language}:${precision}`;
  let formatter = numberFormatters.get(key);
  if (!formatter) {
    formatter = new Intl.NumberFormat(language, {
      minimumFractionDigits: precision,
      maximumFractionDigits: precision,
    });
    numberFormatters.set(key, formatter);
  }
  return formatter.format(value);
}
